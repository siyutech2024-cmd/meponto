/**
 * Tri-lingual user-facing text (zh / en / pt) per the MePonto harness rule #7.
 * Default language is Portuguese (Brazil-facing). The user switches at runtime
 * in Profile; the choice is persisted in SharedPreferences.
 */
enum class AppLanguage(val code: String, val nativeName: String, val flag: String) {
    PT("pt", "Português", "🇧🇷"),
    EN("en", "English", "🇺🇸"),
    ZH("zh", "中文", "🇨🇳");

    companion object {
        fun from(code: String?): AppLanguage = entries.firstOrNull { it.code == code } ?: PT
    }
}

class LocalizationManager(context: Context) {
    private val prefs = context.applicationContext
        .getSharedPreferences("meponto_rider", Context.MODE_PRIVATE)

    init {
        // One-time migration: Portuguese is the product default (Brazil-facing).
        // Applies once per install/upgrade so stale dev-time choices don't stick;
        // after that the user's Profile selection is respected.
        if (!prefs.getBoolean("lang_default_pt_applied", false)) {
            prefs.edit()
                .putString("app_language", "pt")
                .putBoolean("lang_default_pt_applied", true)
                .apply()
        }
    }

    var language by mutableStateOf(AppLanguage.from(prefs.getString("app_language", "pt")))
        private set

    fun updateLanguage(lang: AppLanguage) {
        language = lang
        prefs.edit().putString("app_language", lang.code).apply()
    }

    fun t(key: String): String =
        L10n.table[language]?.get(key) ?: L10n.table[AppLanguage.PT]?.get(key) ?: key
}

